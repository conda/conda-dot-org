"""
Generate markdown documents for each team
"""

import sys

from jinja2 import Environment
from ruamel.yaml import YAML

yaml = YAML()

TEMPLATE = """\
{%- if name == "steering-council" or name == "steering-emeritus" %}
{%- set sidebar_position = 0 %}
{%- elif charter == "static-subteam" %}
{%- set sidebar_position = 1 %}
{%- elif charter == "dynamic-subteam" %}
{%- set sidebar_position = 2 %}
{%- elif charter == "federated-project" or charter == "community-project" %}
{%- set sidebar_position = 3 %}
{%- else %}
{%- set sidebar_position = 4 %}
{%- endif %}
---
sidebar_position: {{ sidebar_position }}
slug: /teams/{{ name }}
---
# {{ name }}

{{ description }}

<!--
This document is autogenerated with bin/render-teams.py in conda/conda-dot-org.
Do not edit manually!
-->

This team is defined as a `{{ charter }}` charter.
{%- if details %}

{{ details }}

{%- endif %}
## Members
{% for member in members %}
* [@{{ member }}](https://github.com/{{ member }})
{%- endfor %}
{%- if emeritus %}
* Emeritus:
{%- for member in emeritus %}
  * [@{{ member }}](https://github.com/{{ member }})
{%- endfor %}
{%- endif %}

{% if resources["other"] or resources["repos"] or resources["teams"] %}
## Resources
{% if resources["teams"] %}
This team is represented by the following Github teams:
{% for team in resources["teams"] %}
* `{{ team }}`
{%- endfor %}
{%- endif %}
{% if resources["repos"] %}
This team has write access to these repositories:
{% for repo in resources["repos"] %}
* [`{{ repo }}`](https://github.com/{{ repo }})
{%- endfor %}
{%- endif %}
{% if resources["other"] %}
Additionally, it controls these other resources:
{% for other in resources["other"] %}
* {{ other }}
{%- endfor %}
{%- endif %}
{%- endif %}
{%- if links %}

## Links
{% for link in links %}
* {{ link }}
{%- endfor %}
{%- endif %}
"""

yml_path = sys.argv[1]
print("Rendering", yml_path, file=sys.stderr)
with open(yml_path) as f:
    data = yaml.load(f)
env = Environment()
tpl = env.from_string(TEMPLATE)
print(tpl.render(data).lstrip())
